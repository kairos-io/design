#!/usr/bin/env node
// Writes tokens.css, tailwind.css and src/tokens/resolved.json from tokens.json. Plain Node, no dependencies.
//
// tokens.json is in the W3C Design Tokens (DTCG) format: a token is an object with $value and $type,
// a group holds tokens (and may carry a $type its tokens inherit), and a "{path.to.token}" value is an
// alias. loadTokens() resolves the aliases and returns a plain view (hex strings, font stacks, px) that
// the generators, scripts/check.cjs and the package's src/tokens read.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const kebab = s => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const HEADER = 'Generated by scripts/build.cjs from tokens.json. Do not edit by hand; run `npm run build`.';

const isToken = n => n && typeof n === 'object' && !Array.isArray(n) && '$value' in n;

// A font stack as CSS: names with spaces or symbols in single quotes, no space after the commas (as the decks write it).
const fontStack = names => names.map(n => (/^[A-Za-z0-9-]+$/.test(n) ? n : `'${n}'`)).join(',');

/** Reads tokens.json and resolves it into the plain view. */
function loadTokens(file = path.join(root, 'tokens.json')) {
  const doc = JSON.parse(fs.readFileSync(file, 'utf8'));

  const lookup = p => {
    let node = doc;
    for (const part of p.split('.')) {
      node = node?.[part];
      if (node === undefined) throw new Error(`tokens.json: alias {${p}} points at nothing`);
    }
    if (!isToken(node)) throw new Error(`tokens.json: alias {${p}} is a group, not a token`);
    return node;
  };
  const value = (v, depth = 0) => {
    if (depth > 20) throw new Error('tokens.json: alias loop');
    if (typeof v === 'string') {
      const m = v.match(/^\{([^}]+)\}$/);
      return m ? value(lookup(m[1]).$value, depth + 1) : v;
    }
    if (Array.isArray(v)) return v.map(x => value(x, depth + 1));
    if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, value(x, depth + 1)]));
    return v;
  };
  // A group as { name: resolvedValue }, skipping $-keys.
  const group = (g, map = x => x) => Object.fromEntries(
    Object.entries(g).filter(([k, v]) => !k.startsWith('$') && isToken(v)).map(([k, v]) => [k, map(value(v.$value))]),
  );
  const ext = doc.$extensions?.['io.kairos.design'] ?? {};

  const variants = {};
  for (const [name, v] of Object.entries(doc.variants)) {
    if (name.startsWith('$')) continue;
    variants[name] = { description: v.$description ?? '', light: group(v.light ?? {}), dark: group(v.dark ?? {}) };
  }
  const size = {};
  for (const [name, t] of Object.entries(doc.font.size)) {
    if (name.startsWith('$')) continue;
    const v = value(t.$value);
    size[name] = { size: v.fontSize, weight: v.fontWeight, tracking: v.letterSpacing, ...(v.lineHeight != null ? { lineHeight: String(v.lineHeight) } : {}) };
  }
  const easing = value(doc.motion.easing.$value);
  return {
    color: { base: group(doc.color.base), brand: group(doc.color.brand), tile: group(doc.color.tile ?? {}), status: group(doc.color.status) },
    themes: { light: group(doc.themes.light), dark: group(doc.themes.dark) },
    variants,
    font: {
      family: group(doc.font.family, fontStack),
      weight: group(doc.font.weight),
      size,
      minSize: value(doc.font['min-size'].$value),
    },
    space: Object.keys(doc.space).filter(k => !k.startsWith('$')).map(Number),
    radius: group(doc.radius),
    layout: group(doc.layout),
    motion: {
      easing: Array.isArray(easing) ? `cubic-bezier(${easing.join(', ')})` : easing,
      scale: value(doc.motion.scale.$value),
      duration: group(doc.motion.duration),
    },
    rules: ext.rules ?? {},
    untokenised: { colors: Object.fromEntries(Object.entries(ext.untokenised?.colors ?? {}).filter(([k]) => !k.startsWith('$'))) },
  };
}

const decls = (obj, indent) => Object.entries(obj).map(([k, v]) => `${indent}--${k}: ${v};`).join('\n');

/** The tokens that are the same in both themes, as { cssName: value }. */
function staticTokens(t) {
  const stat = {};
  for (const [k, v] of Object.entries(t.color.base)) stat[k] = v;
  for (const [k, v] of Object.entries(t.color.brand)) stat[k] = v;
  for (const [k, v] of Object.entries(t.color.tile)) stat[`tile-${k}`] = v;
  for (const [k, v] of Object.entries(t.color.status)) stat[`status-${k}`] = v;
  stat['font-sans'] = t.font.family.sans;
  stat['font-mono'] = t.font.family.mono;
  for (const [k, v] of Object.entries(t.font.weight)) stat[`font-weight-${k}`] = v;
  for (const [k, v] of Object.entries(t.font.size)) {
    stat[`text-${k}`] = v.size;
    stat[`text-${k}-weight`] = v.weight;
    stat[`text-${k}-tracking`] = v.tracking;
    if (v.lineHeight) stat[`text-${k}-line-height`] = v.lineHeight;
  }
  stat['text-min'] = t.font.minSize;
  for (const n of t.space) stat[`space-${n}`] = `${n}px`;
  for (const [k, v] of Object.entries(t.radius)) stat[`radius-${k}`] = v;
  for (const [k, v] of Object.entries(t.layout)) stat[k] = v;
  stat['ease-out'] = t.motion.easing;
  // One scale retimes the whole system: every duration is its value times
  // --duration-scale, so setting that one property on <html> (the Storybook's
  // Motion toolbar, setMotionScale() in a host) slows every transition,
  // animation and tile loop together, and 0 stops them. The
  // prefers-reduced-motion block below sets the durations to a literal 0ms,
  // later in the file, so reduced motion still wins at any scale.
  stat['duration-scale'] = t.motion.scale;
  for (const [k, v] of Object.entries(t.motion.duration)) stat[`duration-${k}`] = `calc(${v} * var(--duration-scale))`;
  return stat;
}

/** Every custom property name tokens.css defines, for the deck check. */
function tokenNames(t) {
  const names = new Set(Object.keys(staticTokens(t)));
  for (const mode of ['light', 'dark']) Object.keys(t.themes[mode]).forEach(n => names.add(n));
  for (const v of Object.values(t.variants)) for (const mode of ['light', 'dark']) Object.keys(v[mode]).forEach(n => names.add(n));
  return names;
}

function tokensCss(t) {
  const out = [`/* ${HEADER} */`, ''];
  const stat = staticTokens(t);
  const light = t.themes.light, dark = t.themes.dark;
  out.push('/* Light is the default. Dark follows [data-theme="dark"], or the system setting when [data-theme] is not "light". */');
  out.push(':root,\n[data-theme="light"] {', decls(stat, '  '), decls(light, '  '), '  color-scheme: light;', '}', '');

  // Variants (light values). Each variant sets every name it changes in either theme.
  const vnames = {};
  for (const [name, v] of Object.entries(t.variants)) vnames[name] = [...new Set([...Object.keys(v.light), ...Object.keys(v.dark)])];
  const vvals = (name, mode) => Object.fromEntries(vnames[name].map(n => [n, t.variants[name][mode][n] ?? t.themes[mode][n]]));
  for (const name of Object.keys(t.variants)) {
    if (!vnames[name].length) continue;
    out.push(`/* variant: ${name}. ${t.variants[name].description} */`);
    out.push(`[data-variant="${name}"] {`, decls(vvals(name, 'light'), '  '), '}', '');
  }

  out.push('[data-theme="dark"] {', decls(dark, '  '), '  color-scheme: dark;', '}', '');
  for (const name of Object.keys(t.variants)) {
    if (!vnames[name].length) continue;
    out.push(`[data-theme="dark"][data-variant="${name}"],\n[data-theme="dark"] [data-variant="${name}"]:not([data-theme="light"]) {`, decls(vvals(name, 'dark'), '  '), '}', '');
  }

  const ind = '    ';
  out.push('@media (prefers-color-scheme: dark) {');
  out.push('  :root:not([data-theme="light"]) {', decls(dark, ind), `${ind}color-scheme: dark;`, '  }');
  for (const name of Object.keys(t.variants)) {
    if (!vnames[name].length) continue;
    out.push(`  :root:not([data-theme="light"])[data-variant="${name}"],\n  :root:not([data-theme="light"]) [data-variant="${name}"]:not([data-theme="light"]) {`, decls(vvals(name, 'dark'), ind), '  }');
  }
  out.push('}', '');
  out.push('@media (prefers-reduced-motion: reduce) {', '  :root {', decls(Object.fromEntries(Object.keys(t.motion.duration).map(k => [`duration-${k}`, '0ms'])), ind), '  }', '}', '');
  return out.join('\n');
}

function tailwindCss(t) {
  const out = [`/* ${HEADER} */`, '@import "./tokens.css";', ''];
  out.push('/* Theme colors follow light and dark through the CSS variables, so they use `inline`. */');
  out.push('@theme inline {');
  for (const name of Object.keys(t.themes.light)) out.push(`  --color-${kebab(name)}: var(--${name});`);
  out.push('}', '');
  out.push('@theme {');
  out.push('  /* Brand and status colors do not change with the theme. */');
  for (const [k, v] of Object.entries(t.color.base)) out.push(`  --color-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.color.brand)) out.push(`  --color-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.color.tile)) out.push(`  --color-tile-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.color.status)) out.push(`  --color-status-${k}: ${v};`);
  out.push('', `  --font-sans: ${t.font.family.sans};`);
  out.push(`  --font-mono: ${t.font.family.mono};`, '');
  for (const [k, v] of Object.entries(t.font.size)) {
    out.push(`  --text-${k}: ${v.size};`);
    out.push(`  --text-${k}--font-weight: ${v.weight};`);
    out.push(`  --text-${k}--letter-spacing: ${v.tracking};`);
    if (v.lineHeight) out.push(`  --text-${k}--line-height: ${v.lineHeight};`);
  }
  out.push('', '  /* The spacing scale is 4, 8, 12, 16, 24, 32, 48, 80 px: p-1, p-2, p-3, p-4, p-6, p-8, p-12, p-20. */');
  out.push('  --spacing: 4px;', '');
  out.push('  /* Radius: 2 for tags, 4 by default, 8 for dialogs. rounded-full stays. */', '  --radius-*: initial;');
  for (const [k, v] of Object.entries(t.radius)) out.push(`  --radius-${k}: ${v};`);
  out.push('', '  /* No shadows. Elevation is a tone step: canvas, surface, raised. */', '  --shadow-*: initial;', '  --drop-shadow-*: initial;', '  --inset-shadow-*: initial;', '');
  out.push(`  --container-page: ${t.layout['page-max']};`, '');
  out.push('  /* Motion: one easing, three durations, each times --duration-scale so one property retimes');
  out.push('     everything; zero under prefers-reduced-motion, whatever the scale (see tokens.css). */');
  out.push(`  --ease-out: ${t.motion.easing};`);
  out.push(`  --duration-scale: ${t.motion.scale};`);
  for (const [k, v] of Object.entries(t.motion.duration)) out.push(`  --duration-${k}: calc(${v} * var(--duration-scale));`);
  out.push('  --animate-fade-up: fade-up var(--duration-slow) var(--ease-out) both;');
  out.push('  --animate-fade-in: fade-in var(--duration-base) var(--ease-out) both;', '');
  out.push('  @keyframes fade-in {', '    from { opacity: 0; }', '    to { opacity: 1; }', '  }');
  out.push('  @keyframes fade-up {', '    from { opacity: 0; transform: translate3d(0, 8px, 0); }', '    to { opacity: 1; transform: translate3d(0, 0, 0); }', '  }');
  out.push('}', '');
  return out.join('\n');
}

/** The resolved view as JSON, for src/tokens (typed by inference) and anything that wants values, not CSS. */
function resolvedJson(t) {
  return JSON.stringify({ $comment: HEADER, ...t }, null, 2) + '\n';
}

function generate(t) {
  return { 'tokens.css': tokensCss(t), 'tailwind.css': tailwindCss(t), 'src/tokens/resolved.json': resolvedJson(t) };
}

module.exports = { generate, loadTokens, tokenNames, root };

if (require.main === module) {
  const files = generate(loadTokens());
  for (const [name, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(root, name), content);
    console.log(`wrote packages/design/${name} (${content.split('\n').length - 1} lines)`);
  }
}
