#!/usr/bin/env node
// Writes tokens.css and tailwind.css from tokens.json. Plain Node, no dependencies.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const kebab = s => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const HEADER = 'Generated by scripts/build.cjs from tokens.json. Do not edit by hand; run `npm run build`.';

function loadTokens() {
  return JSON.parse(fs.readFileSync(path.join(root, 'tokens.json'), 'utf8'));
}

const decls = (obj, indent) => Object.entries(obj).map(([k, v]) => `${indent}--${k}: ${v};`).join('\n');

function tokensCss(t) {
  const out = [`/* ${HEADER} */`, ''];

  // Static tokens: the same in both themes.
  const stat = {};
  for (const [k, v] of Object.entries(t.color.brand)) stat[k] = v;
  for (const [k, v] of Object.entries(t.color.status)) stat[`status-${k}`] = v;
  stat['font-sans'] = t.font.family.sans;
  stat['font-mono'] = t.font.family.mono;
  for (const [k, v] of Object.entries(t.font.weight)) stat[`font-weight-${k}`] = v;
  for (const [k, v] of Object.entries(t.font.size)) {
    stat[`text-${k}`] = v.size;
    stat[`text-${k}-weight`] = v.weight;
    stat[`text-${k}-tracking`] = v.tracking;
    if (v.lineHeight) stat[`text-${k}-line-height`] = v.lineHeight;
  }
  stat['text-min'] = t.font.minSize;
  for (const n of t.space) stat[`space-${n}`] = `${n}px`;
  for (const [k, v] of Object.entries(t.radius)) stat[`radius-${k}`] = v;
  for (const [k, v] of Object.entries(t.layout)) stat[k] = v;
  stat['ease-out'] = t.motion.easing;
  for (const [k, v] of Object.entries(t.motion.duration)) stat[`duration-${k}`] = v;

  const light = t.themes.light, dark = t.themes.dark;
  out.push('/* Light is the default. Dark follows [data-theme="dark"], or the system setting when [data-theme] is not "light". */');
  out.push(':root,\n[data-theme="light"] {', decls(stat, '  '), decls(light, '  '), '  color-scheme: light;', '}', '');

  // Variants (light values). Each variant sets every name it changes in either theme.
  const vnames = {};
  for (const [name, v] of Object.entries(t.variants)) vnames[name] = [...new Set([...Object.keys(v.light), ...Object.keys(v.dark)])];
  const vvals = (name, mode) => Object.fromEntries(vnames[name].map(n => [n, t.variants[name][mode][n] ?? t.themes[mode][n]]));
  for (const name of Object.keys(t.variants)) {
    if (!vnames[name].length) continue;
    out.push(`/* variant: ${name}. ${t.variants[name].description} */`);
    out.push(`[data-variant="${name}"] {`, decls(vvals(name, 'light'), '  '), '}', '');
  }

  out.push('[data-theme="dark"] {', decls(dark, '  '), '  color-scheme: dark;', '}', '');
  for (const name of Object.keys(t.variants)) {
    if (!vnames[name].length) continue;
    out.push(`[data-theme="dark"][data-variant="${name}"],\n[data-theme="dark"] [data-variant="${name}"]:not([data-theme="light"]) {`, decls(vvals(name, 'dark'), '  '), '}', '');
  }

  const ind = '    ';
  out.push('@media (prefers-color-scheme: dark) {');
  out.push('  :root:not([data-theme="light"]) {', decls(dark, ind), `${ind}color-scheme: dark;`, '  }');
  for (const name of Object.keys(t.variants)) {
    if (!vnames[name].length) continue;
    out.push(`  :root:not([data-theme="light"])[data-variant="${name}"],\n  :root:not([data-theme="light"]) [data-variant="${name}"]:not([data-theme="light"]) {`, decls(vvals(name, 'dark'), ind), '  }');
  }
  out.push('}', '');
  out.push('@media (prefers-reduced-motion: reduce) {', '  :root {', decls(Object.fromEntries(Object.keys(t.motion.duration).map(k => [`duration-${k}`, '0ms'])), ind), '  }', '}', '');
  return out.join('\n');
}

function tailwindCss(t) {
  const out = [`/* ${HEADER} */`, '@import "./tokens.css";', ''];
  out.push('/* Theme colors follow light and dark through the CSS variables, so they use `inline`. */');
  out.push('@theme inline {');
  for (const name of Object.keys(t.themes.light)) out.push(`  --color-${kebab(name)}: var(--${name});`);
  out.push('}', '');
  out.push('@theme {');
  out.push('  /* Brand and status colors do not change with the theme. */');
  for (const [k, v] of Object.entries(t.color.brand)) out.push(`  --color-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.color.status)) out.push(`  --color-status-${k}: ${v};`);
  out.push('', `  --font-sans: ${t.font.family.sans};`);
  out.push(`  --font-mono: ${t.font.family.mono};`, '');
  for (const [k, v] of Object.entries(t.font.size)) {
    out.push(`  --text-${k}: ${v.size};`);
    out.push(`  --text-${k}--font-weight: ${v.weight};`);
    out.push(`  --text-${k}--letter-spacing: ${v.tracking};`);
    if (v.lineHeight) out.push(`  --text-${k}--line-height: ${v.lineHeight};`);
  }
  out.push('', '  /* The spacing scale is 4, 8, 12, 16, 24, 32, 48, 80 px: p-1, p-2, p-3, p-4, p-6, p-8, p-12, p-20. */');
  out.push('  --spacing: 4px;', '');
  out.push('  /* Radius: 2 for tags, 4 by default, 8 for dialogs. rounded-full stays. */', '  --radius-*: initial;');
  for (const [k, v] of Object.entries(t.radius)) out.push(`  --radius-${k}: ${v};`);
  out.push('', '  /* No shadows. Elevation is a tone step: canvas, surface, raised. */', '  --shadow-*: initial;', '  --drop-shadow-*: initial;', '  --inset-shadow-*: initial;', '');
  out.push(`  --container-page: ${t.layout['page-max']};`, '');
  out.push('  /* Motion: one easing, three durations, zero under prefers-reduced-motion (see tokens.css). */');
  out.push(`  --ease-out: ${t.motion.easing};`);
  for (const [k, v] of Object.entries(t.motion.duration)) out.push(`  --duration-${k}: ${v};`);
  out.push('  --animate-fade-up: fade-up var(--duration-slow) var(--ease-out) both;');
  out.push('  --animate-fade-in: fade-in var(--duration-base) var(--ease-out) both;', '');
  out.push('  @keyframes fade-in {', '    from { opacity: 0; }', '    to { opacity: 1; }', '  }');
  out.push('  @keyframes fade-up {', '    from { opacity: 0; transform: translate3d(0, 8px, 0); }', '    to { opacity: 1; transform: translate3d(0, 0, 0); }', '  }');
  out.push('}', '');
  return out.join('\n');
}

function generate(t) {
  return { 'tokens.css': tokensCss(t), 'tailwind.css': tailwindCss(t) };
}

module.exports = { generate, loadTokens, root };

if (require.main === module) {
  const files = generate(loadTokens());
  for (const [name, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(root, name), content);
    console.log(`wrote packages/design/${name} (${content.split('\n').length - 1} lines)`);
  }
}
