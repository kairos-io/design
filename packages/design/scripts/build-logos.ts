// Turns the logo artwork in src/assets/logos into the inline-SVG data that
// src/components/Logo/logos.generated.ts renders. Run with
// `node scripts/build-logos.ts` after changing an asset. The shapes and fills
// are copied unchanged: the artwork is the brand.
//
// Two brands, one scheme: <brand>-<layout>-<rendition>.svg. The Kairos files
// are the CNCF artwork (icon, horizontal, stacked; color, white, black) plus
// the dark-surface lockup from the decks (horizontal-dark: colour mark, white
// wordmark). The Hadron files are the decks' (icon color and white; the
// horizontal lockup for light and for dark surfaces). Kairos keys stay
// unprefixed ("icon-color"); Hadron keys carry the brand ("hadron-icon-color").
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const assets = resolve(root, "src/assets/logos");

const shapeTags = ["rect", "path", "polygon", "polyline", "circle", "ellipse", "line"] as const;
type ShapeTag = (typeof shapeTags)[number];
type Shape = { tag: ShapeTag; attrs: Record<string, string> };
type Logo = { viewBox: string; width: number; height: number; shapes: Shape[] };

const attrNames: Record<string, string> = {
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
};

function parse(file: string, svg: string): Logo {
  const head = svg.match(/<svg([^>]*)>/)?.[1] ?? "";
  const viewBox = head.match(/viewBox="([^"]+)"/)?.[1] ?? "";
  const [, , w, h] = viewBox.split(" ").map(Number);
  // A group that carries attributes (a transform, a fill) would change what
  // its children mean once flattened; none of the artwork has one.
  for (const g of svg.matchAll(/<g\b([^>]*)>/g)) {
    if (g[1].trim()) throw new Error(`${file}: <g${g[1]}> has attributes; flatten the artwork first`);
  }
  for (const other of svg.matchAll(/<(defs|use|text|linearGradient|radialGradient|clipPath|mask|image)\b/g)) {
    throw new Error(
      `${file}: <${other[1]}> is not supported by the Logo component; flatten the artwork first`,
    );
  }
  const shapes: Shape[] = [];
  const tagPattern = new RegExp(`<(${shapeTags.join("|")})\\b([^>]*?)\\s*/?>`, "g");
  for (const m of svg.matchAll(tagPattern)) {
    const attrs: Record<string, string> = {};
    for (const a of m[2].matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
      attrs[attrNames[a[1]] ?? a[1]] = a[2];
    }
    shapes.push({ tag: m[1] as ShapeTag, attrs });
  }
  if (!shapes.length) throw new Error(`${file}: no shapes found`);
  return { viewBox, width: w, height: h, shapes };
}

const out: Record<string, Logo> = {};
for (const file of readdirSync(assets).sort()) {
  const m = file.match(/^(kairos|hadron)-(icon|horizontal|stacked)-(color|dark|white|black)\.svg$/);
  if (!m) continue;
  const key = m[1] === "kairos" ? `${m[2]}-${m[3]}` : `${m[1]}-${m[2]}-${m[3]}`;
  out[key] = parse(file, readFileSync(resolve(assets, file), "utf8"));
}

const ts = `// Generated by scripts/build-logos.ts from src/assets/logos. Do not edit.
export type LogoShape = {
  tag: ${shapeTags.map((t) => JSON.stringify(t)).join(" | ")};
  attrs: Record<string, string>;
};
export type LogoData = { viewBox: string; width: number; height: number; shapes: LogoShape[] };

export const logos: Record<string, LogoData> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(resolve(root, "src/components/Logo/logos.generated.ts"), ts);
console.log(`wrote src/components/Logo/logos.generated.ts (${Object.keys(out).length} logos)`);
